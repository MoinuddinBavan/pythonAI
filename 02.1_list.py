# 📒 List = Notebook
# You can:
# ✔ Write
# ✔ Erase
# ✔ Add Pages
# ✔ Remove Pages
# ✔ Change Anything


# 📖 Tuple = Printed Book
# You can:
# ✔ Read
# ✔ Search
# ✔ Count
# ✔ Loop
#
# But...
# ❌ Cannot Edit
# ❌ Cannot Add Pages
# ❌ Cannot Remove Pages

# list = [10, 20, 10, 40, 50]
# tuple = (10, 20, 10, 40, 50)
# set = {10, 20, 10, 40, 50}

# 🎒 Set = Shopping Basket
# You can:
# ✔ Keep Only Unique Items
# ✔ Add Items
# ✔ Remove Items
# ✔ Check Item Exists
# ✔ Loop Through Items
#
# But...
# ❌ Cannot Keep Duplicate Items
# ❌ Cannot Access by Index
# ❌ Items Have No Fixed Position


# One-Line Memory
# 📒 List   = Editable Collection
# 📖 Tuple  = Read-Only Collection
# 🎒 Set    = Unique Collection

# 🔥 The Golden Rule (Remember Forever)
# 📒 List  = I want to CHANGE data.
# 📖 Tuple = I DON'T want anyone to change the data.
# 🎒 Set   = I DON'T want duplicate data.

print("\n====================================================")
print("1. Create List")
print("====================================================")

fruits = ["Apple", "Mango", "Orange", "Banana", "Kiwi"]

print(fruits)


# =====================================================
# 2. Access List Items
# =====================================================

print("\n====================================================")
print("2. Access List Items")
print("====================================================")

print("First Fruit :", fruits[0])
print("Second Fruit:", fruits[1])
print("Last Fruit  :", fruits[-1])


# =====================================================
# 3. Change Item
# =====================================================

print("\n====================================================")
print("3. Change Item")
