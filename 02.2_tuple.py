# =====================================================
# 1. Create Tuple
# =====================================================

print("\n====================================================")
print("1. Create Tuple")
print("====================================================")

fruits = ("Apple", "Mango", "Orange", "Banana")

print(fruits)


# =====================================================
# 2. Access Tuple Items
# =====================================================

print("\n====================================================")
print("2. Access Tuple Items")
print("====================================================")

print("First Fruit :", fruits[0])
print("Second Fruit:", fruits[1])
print("Last Fruit  :", fruits[-1])


# =====================================================
# 3. Tuple Length
# =====================================================

print("\n====================================================")
print("3. Tuple Length")
print("====================================================")

print(len(fruits))


# =====================================================
# 4. Loop Through Tuple
# =====================================================

print("\n====================================================")
print("4. Loop Through Tuple")
print("====================================================")

for fruit in fruits:
    print(fruit)


# =====================================================
# 5. Check Item Exists
# =====================================================

print("\n====================================================")
print("5. Check Item Exists")
print("====================================================")

print("Apple" in fruits)
print("Kiwi" in fruits)


# =====================================================
# 6. Tuple Slicing
# =====================================================

print("\n====================================================")
print("6. Tuple Slicing")
print("====================================================")

numbers = (10, 20, 30, 40, 50, 60)

print(numbers[1:4])
print(numbers[:3])
print(numbers[2:])
print(numbers[-3:])


# =====================================================
# 7. Count
# =====================================================

print("\n====================================================")
print("7. Count")
print("====================================================")

numbers = (10, 20, 10, 30, 10, 40)

print(numbers.count(10))


# =====================================================
# 8. Index
# =====================================================

print("\n====================================================")
print("8. Index")
print("====================================================")

print(fruits.index("Orange"))


# =====================================================
# 9. Duplicate Values
# =====================================================

print("\n====================================================")
print("9. Duplicate Values")
print("====================================================")

numbers = (1, 2, 2, 3, 3, 3)

print(numbers)


# =====================================================
# 10. Nested Tuple
# =====================================================

print("\n====================================================")
print("10. Nested Tuple")
print("====================================================")

students = (
    ("Moin", 90),
    ("Ali", 80),
    ("Aamir", 95)
)

print(students)
print(students[0])
print(students[0][0])
print(students[0][1])


# =====================================================
# 11. Tuple Concatenation
# =====================================================

print("\n====================================================")
print("11. Tuple Concatenation")
print("====================================================")

tuple1 = (1, 2, 3)
tuple2 = (4, 5, 6)

tuple3 = tuple1 + tuple2

print(tuple3)


# =====================================================
# 12. Tuple Repetition
# =====================================================

print("\n====================================================")
print("12. Tuple Repetition")
print("====================================================")

letters = ("A",)

print(letters * 5)


# =====================================================
# 13. Convert List to Tuple
# =====================================================

print("\n====================================================")
print("13. List to Tuple")
print("====================================================")

my_list = ["Red", "Green", "Blue"]

my_tuple = tuple(my_list)

print(my_tuple)


# =====================================================
# 14. Convert Tuple to List
# =====================================================

print("\n====================================================")
print("14. Tuple to List")
print("====================================================")

colors = list(my_tuple)

print(colors)


# =====================================================
# 15. Unpacking Tuple
# =====================================================

print("\n====================================================")
print("15. Tuple Unpacking")
print("====================================================")

person = ("Moin", 32, "Ahmedabad")

name, age, city = person

print(name)
print(age)
print(city)


