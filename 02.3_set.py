print(len(fruits))


# =====================================================
# 4. Loop Through Set
# =====================================================

print("\n====================================================")
print("4. Loop Through Set")
print("====================================================")

for fruit in fruits:
    print(fruit)


# =====================================================
# 5. Check Item Exists
# =====================================================

print("\n====================================================")
print("5. Check Item Exists")
print("====================================================")

print("Apple" in fruits)
print("Banana" in fruits)


# =====================================================
# 6. Add Item
# =====================================================

print("\n====================================================")
print("6. Add Item") # Add an item to a set using the add() method. If the item already exists, it will not be added again.
print("====================================================")

fruits.add("Banana")

print(fruits)


# =====================================================
# 7. Update Set
# =====================================================

print("\n====================================================")
print("7. Update Set") # Add multiple items to a set using the update() method. You can pass any iterable (list, tuple, dictionary, etc.) to the update() method.
print("====================================================")

fruits.update(["Kiwi", "Papaya"])

print(fruits)


# =====================================================
# 8. Remove Item
# =====================================================

print("\n====================================================")
print("8. Remove Item")
print("====================================================")

fruits.remove("Apple")

print(fruits)


# =====================================================
# 9. Discard Item
# =====================================================

print("\n====================================================")
print("9. Discard Item") # Remove the item if it exists. If it doesn't exist, do nothing.
print("====================================================")

fruits.discard("Orange")

print(fruits)


# =====================================================
# 10. Pop Item
# =====================================================

print("\n====================================================")
print("10. Pop Item")
print("====================================================")

removed_item = fruits.pop()

print("Removed:", removed_item)
print(fruits)


# =====================================================
# 11. Copy Set
# =====================================================

print("\n====================================================")
print("11. Copy Set")
print("====================================================")

set1 = {1, 2, 3}

set2 = set1.copy()

print(set1)
print(set2)


# =====================================================
# 12. Clear Set
# =====================================================

print("\n====================================================")
print("12. Clear Set")
print("====================================================")

set2.clear()

print(set2)


# =====================================================
# 13. Union # Everything from both sets
# =====================================================

print("\n====================================================")
print("13. Union") # The union of two sets is a set containing all the elements from both sets, without duplicates.
print("====================================================")

setA = {1, 2, 3}
setB = {3, 4, 5}

print(setA.union(setB))


# =====================================================
# 14. Intersection # Only the common elements from both sets
# =====================================================

print("\n====================================================")
print("14. Intersection")
print("====================================================")

print(setA.intersection(setB))


# =====================================================
# 15. Difference # Only the elements that are in the first set but not in the second set
# =====================================================

print("\n====================================================")
print("15. Difference")
print("====================================================")

print(setA.difference(setB))


# =====================================================
# 16. Symmetric Difference # Values that are NOT common
# =====================================================

print("\n====================================================")
print("16. Symmetric Difference")
print("====================================================")

print(setA.symmetric_difference(setB))


# =====================================================
# 17. Subset
# =====================================================

print("\n====================================================")
print("17. Subset") # Small set inside a big set.
print("====================================================")

small = {1, 2}
large = {1, 2, 3, 4}

print(small.issubset(large))


# =====================================================
# 18. Superset # Big set containing a small set.
# =====================================================

print("\n====================================================")
print("18. Superset")
print("====================================================")

print(large.issuperset(small))


