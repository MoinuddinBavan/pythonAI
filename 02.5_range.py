# =====================================================
# 1. Create Range
# =====================================================

print("\n====================================================")
print("1. Create Range")
print("====================================================")

numbers = range(5)

print(numbers)


# =====================================================
# 2. Convert to List
# =====================================================

print("\n====================================================")
print("2. Convert to List")
print("====================================================")

print(list(numbers))


# =====================================================
# 3. Start and Stop
# =====================================================

print("\n====================================================")
print("3. Start and Stop")
print("====================================================")

print(list(range(1, 6)))


# =====================================================
# 4. Step
# =====================================================

print("\n====================================================")
print("4. Step")  # range(start, stop, step)
print("====================================================")

print(list(range(2, 11, 2))) # Even numbers from 2 to 10


# =====================================================
# 5. Reverse Range
# =====================================================

print("\n====================================================")
print("5. Reverse Range")
print("====================================================")

print(list(range(10, 0, -1))) # Reverse numbers from 10 to 1


# =====================================================
# 6. Loop Using Range
# =====================================================

print("\n====================================================")
print("6. Loop Using Range")
print("====================================================")

for number in range(1, 6):
    print(number)


# =====================================================
# 7. Even Numbers
# =====================================================

print("\n====================================================")
print("7. Even Numbers")
print("====================================================")

for number in range(2, 21, 2): # Even numbers from 2 to 20
    print(number)


# =====================================================
# 8. Odd Numbers
# =====================================================

print("\n====================================================")
print("8. Odd Numbers")
print("====================================================")

for number in range(1, 20, 2): # Odd numbers from 1 to 19
    print(number)


# =====================================================
# 9. Multiplication Table
# =====================================================

print("\n====================================================")
print("9. Multiplication Table")
print("====================================================")

for number in range(1, 11):
    print("5 x", number, "=", 5 * number)


# =====================================================
# 10. Sum Using Range
# =====================================================

print("\n====================================================")
print("10. Sum Using Range")
print("====================================================")

total = 0

for number in range(1, 11):
    total += number

print(total)


# =====================================================
# 11. Range with len()
# =====================================================

print("\n====================================================")
print("11. Range with len()")
print("====================================================")

print(len(range(1, 11)))


# =====================================================
# 12. Indexing
# =====================================================

print("\n====================================================")
print("12. Indexing")
print("====================================================")

numbers = range(10)

print(numbers[0])
print(numbers[5])
print(numbers[-1])


# =====================================================
# 13. Membership
# =====================================================

print("\n====================================================")
print("13. Membership")
print("====================================================")

print(5 in range(10))
print(20 in range(10))


# =====================================================
# 14. Slice Range
# =====================================================

print("\n====================================================")
print("14. Slice Range")
print("====================================================")

numbers = range(20)

print(list(numbers[5:10]))


