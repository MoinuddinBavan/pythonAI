# Comments, Escape Sequences & Print Statement

print("Hello World") # This is a comment

# Escape Sequences characters -> \n, \t, \", \\
# Example of \n this is new line 
print("Hello world \n i am moin")

# Example of \t this is tab 
print("Hello world \t i am moin")

# Example of \" this is used for double quote to print 
print("Hello world \" i am moin")

# Example of \\ this is used for printing backslash 
print("Hello world \\ i am moin") 


# Print => print multiple values
print("Hello", 99, "World", sep="`")




